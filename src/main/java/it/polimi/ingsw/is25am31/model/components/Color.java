/**
 * Enumeration representing the available colors in the game.
 * This enum defines the four primary colors that can be used throughout
 * the game system. Each color represents a distinct visual identifier that
 * can be associated with game components, players, or other elements requiring
 * color-based differentiation.
 * The available colors are:
 * {@link #BLUE} - Blue color,
 * {@link #GREEN} - Green color,
 * {@link #RED} - Red color,
 * {@link #YELLOW} - Yellow color.
 */
public enum Color {
    BLUE, GREEN, RED, YELLOW;
}
