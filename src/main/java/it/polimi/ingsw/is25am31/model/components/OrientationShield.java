package it.polimi.ingsw.is25am31.model.components;

/**
 * Enumeration representing the four diagonal orientations for shield components.
 * The available shield orientations are:
 * {@link #UPLEFT} - Upper-left diagonal orientation,
 * {@link #UPRIGHT} - Upper-right diagonal orientation,
 * {@link #DOWNRIGHT} - Lower-right diagonal orientation,
 * {@link #DOWNLEFT} - Lower-left diagonal orientation.
 * @see Side
 */
public enum OrientationShield {
    UPRIGHT, DOWNRIGHT, DOWNLEFT, UPLEFT
}
